CREATE DATABASE IF NOT EXISTS LOGIN_1;
USE LOGIN_1;

CREATE TABLE IF NOT EXISTS users (
    id INT AUTO_INCREMENT PRIMARY KEY,
    USERNAME VARCHAR(50) UNIQUE NOT NULL,
    EMAIL VARCHAR(100) UNIQUE NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL,
    PROFILE_PIC VARCHAR(255) DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS suppliers (
    id INT AUTO_INCREMENT PRIMARY KEY,
    supplier_name VARCHAR(100) NOT NULL UNIQUE,
    contact_person VARCHAR(100),
    contact_number VARCHAR(20),
    email VARCHAR(100),
    address TEXT,
    medicines_supplied TEXT
);

CREATE TABLE IF NOT EXISTS medicine (
    id INT AUTO_INCREMENT PRIMARY KEY,
    MEDICINE_ID VARCHAR(50) NOT NULL,
    MEDICINE_NAME VARCHAR(100) NOT NULL,
    BATCH_NO VARCHAR(50),
    CATEGORY VARCHAR(50),
    EXPIRY_DATE DATE,
    PRICE DECIMAL(10, 2) NOT NULL,
    PURCHASE_PRICE DECIMAL(10, 2) DEFAULT 0.00,
    STOCK_QUANTITY INT DEFAULT 0,
    PURCHASE_DATE DATE,
    SUPPLIER_NAME VARCHAR(100),
    FOREIGN KEY (SUPPLIER_NAME) REFERENCES suppliers(supplier_name) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS purchases (
    id INT AUTO_INCREMENT PRIMARY KEY,
    med_id INT,
    supplier_name VARCHAR(100),
    quantity INT NOT NULL,
    unit_price DECIMAL(10, 2) NOT NULL,
    total_cost DECIMAL(10, 2) NOT NULL,
    purchase_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (med_id) REFERENCES medicine(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS sales (
    id INT AUTO_INCREMENT PRIMARY KEY,
    MED_ID INT,
    MEDICINE_NAME VARCHAR(100),
    QUANTITY INT NOT NULL,
    TOTAL_PRICE DECIMAL(10, 2) NOT NULL,
    PROFIT DECIMAL(10, 2) NOT NULL,
    CUSTOMER_NAME VARCHAR(100),
    INVOICE_NO VARCHAR(50) UNIQUE,
    SALE_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (MED_ID) REFERENCES medicine(id) ON DELETE SET NULL
);

-- Pre-calculated days until expiry for each medicine, used by the /expiry page.
CREATE OR REPLACE VIEW expiry_tracking AS
SELECT id, MEDICINE_ID, MEDICINE_NAME, BATCH_NO, CATEGORY, EXPIRY_DATE, PRICE,
       PURCHASE_PRICE, STOCK_QUANTITY, PURCHASE_DATE, SUPPLIER_NAME,
       DATEDIFF(EXPIRY_DATE, CURDATE()) AS DAYS_LEFT
FROM medicine;
